param([string]$ResRoot = (Join-Path $PSScriptRoot '..\core\designsystem\src\main\res'))
$ErrorActionPreference = 'Stop'
$directories = @('values-en', 'values-ca', 'values-de', 'values-fr', 'values-it', 'values-ja', 'values-nl', 'values-pt', 'values-zh-rCN')
$rows = @(Get-Content (Join-Path $PSScriptRoot 'android-fallback-translations.txt') -Encoding utf8 | Where-Object { $_.Trim() } | ForEach-Object { ,($_ -split '\|', 10) })
[xml]$fallbacks = Get-Content (Join-Path $ResRoot 'values\android_translation_fallbacks.xml') -Raw -Encoding utf8
$source = @{}
foreach ($entry in $fallbacks.resources.string) { $source[$entry.name] = $entry.'#text' }
foreach ($row in $rows) {
    if ($row.Count -ne 10 -or @($row | Where-Object { [string]::IsNullOrWhiteSpace($_) }).Count) { throw "Incomplete fallback translation: $($row[0])" }
    if (!$source.ContainsKey($row[0]) -or $source[$row[0]] -like '@string/*') { throw "Unknown or aliased fallback: $($row[0])" }
    $expected = @([regex]::Matches($source[$row[0]], '%\d+\$[sd]') | ForEach-Object Value | Sort-Object) -join ','
    foreach ($value in $row[1..9]) {
        $actual = @([regex]::Matches($value, '%\d+\$[sd]') | ForEach-Object Value | Sort-Object) -join ','
        if ($actual -ne $expected) { throw "Mismatched format arguments in $($row[0]): expected $expected; found $actual" }
    }
}
if (@($rows | ForEach-Object { $_[0] } | Select-Object -Unique).Count -ne $rows.Count) { throw 'Duplicate fallback translation key' }
for ($index = 0; $index -lt $directories.Count; $index++) {
    $directory = Join-Path $ResRoot $directories[$index]
    New-Item -ItemType Directory -Force -Path $directory | Out-Null
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('<?xml version="1.0" encoding="utf-8"?>')
    $lines.Add('<!-- Generated by scripts/sync-android-fallback-translations.ps1. -->')
    $lines.Add('<resources>')
    foreach ($row in $rows) {
        $value = $row[$index + 1].Replace('\', '\\').Replace("'", "\'").Replace('"', '\"')
        $value = [Security.SecurityElement]::Escape($value)
        $lines.Add("    <string name=`"$($row[0])`" formatted=`"false`">$value</string>")
    }
    $lines.Add('</resources>')
    [IO.File]::WriteAllLines((Join-Path $directory 'android_fallback_translations.xml'), $lines, [Text.UTF8Encoding]::new($false))
}
Write-Output "Generated $($rows.Count) fallback translations for $($directories.Count) languages."
