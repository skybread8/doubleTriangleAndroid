param(
    [string]$ProjectRoot = (Join-Path $PSScriptRoot '..')
)
$ErrorActionPreference = 'Stop'
$catalog = Get-Content (Join-Path $ProjectRoot 'feature\workout\src\main\res\raw\exercise_tutorial_labels.json') -Raw -Encoding utf8 | ConvertFrom-Json -AsHashtable
[xml]$sheet = Get-Content (Join-Path $ProjectRoot 'core\designsystem\src\main\res\values\sheet_translations.xml') -Raw -Encoding utf8
$sheetValues = @{}; foreach ($item in $sheet.resources.string) { $sheetValues[$item.name] = $item.'#text' }
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('package io.codepassion.doubletriangle.feature.workout')
$lines.Add('')
$lines.Add('// Generated by scripts/sync-sheet-tutorial-map.ps1. Do not edit manually.')
$lines.Add('internal val sharedTutorialTextResources: Map<String, Int> = mapOf(')
$count = 0
foreach ($key in ($catalog.texts.Keys | Sort-Object)) {
    if ($key.Contains('%')) { continue }
    $name = [regex]::Replace($key.Replace('-','_').Replace(' ','_').ToLowerInvariant(), '[^a-z0-9_]', '_')
    if (!$name -or !$sheetValues.ContainsKey($name)) { continue }
    $value = $sheetValues[$name].Replace("\'", "'").Replace('\"','"').Replace('\\','\')
    if ($value -ine $key) { continue }
    $escaped = $key.Replace('\','\\').Replace('"','\"').Replace('$','\$').Replace("`r",'\r').Replace("`n",'\n')
    $lines.Add("    `"$escaped`" to io.codepassion.doubletriangle.core.designsystem.R.string.``$name``,")
    $count++
}
$lines.Add(')')
$output = Join-Path $ProjectRoot 'feature\workout\src\main\java\io\codepassion\doubletriangle\feature\workout\SharedTutorialTextMap.kt'
[IO.File]::WriteAllLines($output, $lines, [Text.UTF8Encoding]::new($false))
Write-Output "Mapped $count tutorial keys to shared Sheet resources."
